#!/usr/bin/env bash
# Build phase3-ota with a unique build id and publish it for OTA.
#
#   tools/deploy_ota.sh               build + publish (device installs it next cycle)
#   tools/deploy_ota.sh --usb PORT    build + publish + flash the same image over USB
#   tools/deploy_ota.sh --build       build only (nothing published)
#
# Needs tools/secrets.env (see tools/secrets.env.example). Generates the
# gitignored phase3-ota/secrets.h from it on every run.
set -euo pipefail
cd "$(dirname "$0")/.."
set -a; . tools/secrets.env; set +a

SKETCH=phase3-ota
FQBN="esp32:esp32:esp32:UploadSpeed=921600,FlashSize=4M,PartitionScheme=min_spiffs"
USB_PORT=""; PUBLISH=1
case "${1:-}" in
  --usb)   USB_PORT="${2:?usage: --usb PORT}" ;;
  --build) PUBLISH=0 ;;
  "")      ;;
  *)       echo "usage: $0 [--usb PORT | --build]" >&2; exit 2 ;;
esac

dirty=$([ -z "$(git status --porcelain -- "$SKETCH")" ] && echo "" || echo "+")
BUILD="$(date -u +%Y%m%d-%H%M%S)-$(git rev-parse --short HEAD)$dirty"
OUT="build/$BUILD"

cat > "$SKETCH/secrets.h" <<EOF
// Generated by tools/deploy_ota.sh from tools/secrets.env — do not edit or commit.
#pragma once
#define SECRET_DEVICE_ID "$DEVICE_ID"
#define SECRET_MQTT_HOST "$MQTT_HOST"
#define SECRET_MQTT_PORT $MQTT_PORT
#define SECRET_MQTT_PASS "$DEVICE_MQTT_PASS"
#define SECRET_OTA_HOST  "$VPS_HOST"
#define SECRET_OTA_PORT  $OTA_PORT
#define SECRET_OTA_TOKEN "$OTA_TOKEN"
EOF
echo "#define FW_BUILD \"$BUILD\"" > "$SKETCH/build_id.h"
trap 'rm -f "$SKETCH/build_id.h"' EXIT   # hand builds stay "dev" (no self-update)

arduino-cli compile --fqbn "$FQBN" --output-dir "$OUT" "$SKETCH" | tail -2
BIN="$OUT/$SKETCH.ino.bin"
SIZE=$(stat -c %s "$BIN")
MD5=$(md5sum "$BIN" | cut -d' ' -f1)
FILE="fw-$BUILD.bin"
printf 'version=%s\nfile=%s\nsize=%s\nmd5=%s\n' "$BUILD" "$FILE" "$SIZE" "$MD5" > "$OUT/manifest.txt"

if [ "$PUBLISH" = 1 ]; then
  DIR="bike-backend/www/fw/$OTA_TOKEN"
  # Image first, then swap the manifest in atomically; keep the last 3 images.
  scp -q "$BIN" "$VPS_SSH:$DIR/$FILE"
  scp -q "$OUT/manifest.txt" "$VPS_SSH:$DIR/manifest.txt.tmp"
  ssh -o BatchMode=yes "$VPS_SSH" "cd $DIR && mv manifest.txt.tmp manifest.txt && ls -t fw-*.bin | tail -n +4 | xargs -r rm --"
  echo "published $BUILD ($SIZE bytes, md5 $MD5)"
fi

if [ -n "$USB_PORT" ]; then
  arduino-cli upload -p "$USB_PORT" --fqbn "$FQBN" --input-dir "$OUT" "$SKETCH"
  echo "flashed $BUILD over USB"
fi
